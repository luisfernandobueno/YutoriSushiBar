export function buildServiceStages(language = "en") {
  return SERVICE_STAGES.map((stage) => {
    const content =
      stage.translations[language] || stage.translations.en;

    return {
      id: stage.id,
      category: stage.category,
      difficulty: stage.difficulty,
      ...content,
    };
  });
}

export function getMenuReference(menuData, limit = 8) {
  if (!menuData?.categories) return [];

  const items = [];

  function walk(categories) {
    if (!Array.isArray(categories)) return;

    categories.forEach((category) => {
      if (Array.isArray(category.items)) {
        category.items.forEach((item) => {
          if (!item?.name || typeof item.name !== "string") return;

          items.push({
            name: item.name,
            image: item.img || null,
            price: Number(item.price) || null,
            description: item.description || {},
            category: category.name || "",
          });
        });
      }

      if (Array.isArray(category.subcategories)) {
        walk(category.subcategories);
      }

      if (Array.isArray(category.categories)) {
        walk(category.categories);
      }
    });
  }

  walk(menuData.categories);

  return items.slice(0, limit);
}
